import assert from 'node:assert/strict';
import {assessEligibility,emptyCoverage} from './entitlementCheck.ts';
const base={kind:'maternity',employment:'etat',insured:'tak',coverage:{...emptyCoverage(),startDate:'2026-11-01'},eventDate:'2026-11-21',eventConfirmed:true,debt:'none'};
const mat=assessEligibility(base);
assert.equal(mat.status,'possible','Macierzyński bez okresu wyczekiwania');
const soon=assessEligibility({...base,kind:'pregnancy_sickness',coverage:{...base.coverage,ezlaCodeB:'yes',waitingException:'none'}});
assert.equal(soon.status,'blocked_standard','30 dni dla etat przed wyczekiwaniem');
assert.equal(soon.waitingDays,10);
const after30=assessEligibility({...base,kind:'pregnancy_sickness',eventDate:'2026-12-01',coverage:{...base.coverage,ezlaCodeB:'yes',waitingException:'none'}});
assert.equal(after30.status,'possible');
const contractor=assessEligibility({...base,kind:'pregnancy_sickness',employment:'zlecenie',eventDate:'2026-12-15',coverage:{...base.coverage,ezlaCodeB:'yes',waitingException:'none'}});
assert.equal(contractor.status,'blocked_standard','90 dni dla zlecenia');
const voluntary=assessEligibility({...base,kind:'pregnancy_sickness',employment:'dzialalnosc',eventDate:'2027-02-01',coverage:{...base.coverage,ezlaCodeB:'yes',waitingException:'none'},debt:'none'});
assert.equal(voluntary.status,'possible','90 dni minęło');
const previous=assessEligibility({...base,kind:'pregnancy_sickness',coverage:{...base.coverage,ezlaCodeB:'yes',waitingException:'none',priorCreditedDays:'21',priorPeriodsConfirmed:true}});
assert.equal(previous.status,'possible','Zaliczone okresy po potwierdzeniu');
const previousUnconfirmed=assessEligibility({...base,kind:'pregnancy_sickness',coverage:{...base.coverage,ezlaCodeB:'yes',waitingException:'none',priorCreditedDays:'21',priorPeriodsConfirmed:false}});
assert.equal(previousUnconfirmed.status,'blocked_standard','Brak potwierdzenia poprzedniego okresu nie daje prawa');
const exception=assessEligibility({...base,kind:'pregnancy_sickness',coverage:{...base.coverage,ezlaCodeB:'yes',waitingException:'graduate'}});
assert.equal(exception.status,'review');
const codeB=assessEligibility({...base,kind:'pregnancy_sickness',eventDate:'2026-12-15',coverage:{...base.coverage,ezlaCodeB:'no',waitingException:'none'}});
assert.equal(codeB.status,'review','Brak B uniemożliwia automatyczne 100%');
const debt=assessEligibility({...base,employment:'dzialalnosc',debt:'over'});
assert.equal(debt.status,'blocked_standard','Dług JDG wstrzymuje standardowe świadczenie');
const installments=assessEligibility({...base,employment:'dzialalnosc',debt:'installments',coverage:{...base.coverage,debtAgreementConfirmed:true}});
assert.equal(installments.status,'review','Układ ratalny wymaga sprawdzenia zakresu');
const exit=assessEligibility({...base,coverage:{...base.coverage,endDate:'2026-11-15',postInsuranceException:'none'}});
assert.equal(exit.status,'blocked_standard','Brak ubezpieczenia w dniu porodu i bez wyjątku');
const liquidation=assessEligibility({...base,insured:'nie',coverage:{...base.coverage,endDate:'2026-11-15',postInsuranceException:'liquidation'}});
assert.equal(liquidation.status,'review','Wyjątek art. 30 nie może być automatycznie odrzucony');
const unknown=assessEligibility({...base,coverage:emptyCoverage()});
assert.equal(unknown.status,'review','Brak daty ubezpieczenia musi zostać zweryfikowany');
const uncertainLegal=assessEligibility({...base,kind:'parental',legalParentConfirmed:false});
assert.equal(uncertainLegal.status,'review');
const future=assessEligibility({...base,eventConfirmed:false});
assert.equal(future.status,'review');
console.log('OK: 16 entitlement checks: macierzyński, waiting periods, e-ZLA B, JDG debt, post-insurance and legal uncertainty');
