import assert from 'node:assert/strict';
import {limits,plusDays,calculateLeavePlan} from './leaveRules.ts';
assert.equal(limits(1).maternityDays,140);
assert.equal(limits(2).maternityDays,217);
assert.equal(limits(5).maternityDays,259);
assert.equal(limits(1).parentalDays,287);
assert.equal(limits(2).parentalDays,301);
assert.equal(plusDays('2026-12-01',9),'2026-12-10');
assert.equal(plusDays('2027-01-01',-1),'2026-12-31');
const p=calculateLeavePlan({birthDate:'2026-12-01',children:1,parent1Weeks:32,parent2Weeks:9,secondParentEligible:true});
assert.equal(p.maternity.end,'2027-04-19');
assert.equal(p.parent1Parental?.start,'2027-04-20');
assert.equal(p.parent1Days,224);
assert.equal(p.parent2Days,63);
assert.equal(p.parentalUnusedDays,0);
assert.equal(p.averagedApplicationDeadline,'2026-12-22');
const single=calculateLeavePlan({birthDate:'2026-12-01',children:1,parent1Weeks:32,parent2Weeks:0,secondParentEligible:false});
assert.equal(single.parentalUnusedDays,63);
assert.throws(()=>calculateLeavePlan({birthDate:'2026-12-01',children:1,parent1Weeks:33,parent2Weeks:0,secondParentEligible:false}));
assert.throws(()=>calculateLeavePlan({birthDate:'2026-12-01',children:1,parent1Weeks:32,parent2Weeks:9,secondParentEligible:false}));
console.log('OK: 14 kontrolnych asercji okresów i dat');
