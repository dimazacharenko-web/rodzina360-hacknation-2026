import assert from 'node:assert/strict';
import {emptyCare,calculateCarePlan,calculateCarePeriods,initialCareEntries,careDocuments} from './careRules.ts';
import {calculateMoney} from './paymentEngine.ts';
import {daysInclusive} from './flexibleLeave.ts';
const source={...emptyCare(),acceptanceDate:'2026-12-01',courtFilingDate:'2026-12-01',childBirthDates:['2024-01-01'],schoolDeferred:'no'};
const adopt=calculateCarePlan('adoption',source,1);
assert.equal(adopt.maternityDays,140,'20 weeks one child');
assert.equal(adopt.parentalDays,287,'41 weeks parental');
assert.equal(adopt.ageLimitYears,14);
assert.equal(adopt.averagedDeadline,'2026-12-22');
assert.equal(adopt.employerApplicationDeadline,'2026-12-08');
assert.equal(adopt.leaveStartDeadline,'2026-12-22');
assert.equal(daysInclusive(adopt.maternity.start,adopt.maternity.end),140);
assert.ok(careDocuments(adopt,'etat','averaged').some(x=>x.title.includes('81,5%')));
const both=initialCareEntries(adopt,true);
const plan=calculateCarePeriods(adopt,both,true);
assert.equal(plan.totalDays,287);
assert.deepEqual(plan.plannedByParent,[224,63]);
assert.equal(plan.remainingFamilyDays,0);
const sole=calculateCarePeriods(adopt,initialCareEntries(adopt,false),false);
assert.equal(sole.totalDays,224);
assert.equal(sole.remainingFamilyDays,63);
const money=calculateMoney({maternityDays:adopt.maternityDays,maternityUsedDays:0,parentalEntries:plan.entries,bases:[6000,6000],insured:[true,true],employment:['etat','etat'],debts:['none','none'],variant:'standard',averagedConfirmed:false,special:false,entitlementStatuses:['possible','possible']});
assert.equal(money.parents[0].periods.find(x=>x.type==='maternity').rate,1);
assert.equal(money.parents[0].periods.find(x=>x.type==='parental').rate,.7);
assert.equal(money.parents[1].periods.find(x=>x.type==='parental').rate,.7);
const avg=calculateMoney({maternityDays:adopt.maternityDays,maternityUsedDays:0,parentalEntries:plan.entries,bases:[6000,6000],insured:[true,true],employment:['etat','etat'],debts:['none','none'],variant:'averaged',averagedConfirmed:true,special:false});
assert.equal(avg.parents[0].periods.find(x=>x.type==='maternity').rate,.815);
assert.equal(avg.parents[1].periods.find(x=>x.type==='parental').rate,.7);
const near14=calculateCarePlan('adoption',{...source,childBirthDates:['2013-01-01']},1);
assert.equal(near14.maternityDays,63,'9-week minimum near age 14');
assert.equal(near14.parentalWeeks,38,'38 weeks parental in minimum nine-week case');
assert.deepEqual(initialCareEntries(near14,false),[],'No parental leave after 14th birthday');
assert.equal(calculateCarePeriods(near14,[],false).totalDays,0);
assert.throws(()=>calculateCarePlan('adoption',{...source,courtFilingDate:''},1),/sądu/);
assert.throws(()=>calculateCarePlan('adoption',{...source,childBirthDates:['2012-01-01']},1),/limit wieku/);
assert.equal(calculateCarePlan('adoption',{...source,courtFilingDate:'2026-11-20'},1).eventDate,'2026-12-01');
assert.throws(()=>calculateCarePlan('adoption',{...source,leaveStartDate:'2026-12-30'},1),/21 dni/);
const fosterSource={...source,childBirthDates:['2020-01-01'],courtFilingDate:''};
const foster=calculateCarePlan('foster',fosterSource,1);
assert.equal(foster.ageLimitYears,7);
assert.equal(foster.maternityDays,63,'Foster: 9 weeks near seventh birthday');
assert.equal(foster.parentalWeeks,38);
assert.throws(()=>calculateCarePlan('foster',{...fosterSource,childBirthDates:['2019-01-01']},1),/limit wieku/);
const fosterWithDelay=calculateCarePlan('foster',{...fosterSource,childBirthDates:['2019-01-01'],schoolDeferred:'yes'},1);
assert.equal(fosterWithDelay.ageLimitYears,10);
assert.equal(fosterWithDelay.maternityDays,140);
assert.throws(()=>calculateCarePlan('foster',{...fosterSource,schoolDeferred:'unknown'},1),/obowiązek szkolny/);
assert.throws(()=>calculateCarePlan('foster',{...fosterSource,fosterType:'professional'},1),/niezawodow/);
const mixed=calculateCarePlan('adoption',{...source,childBirthDates:['2021-01-01','2022-01-01']},2);
assert.equal(mixed.maternityDays,217);
assert.equal(mixed.parentalWeeks,43);
assert.equal(mixed.review,true,'Multiple ages require manual verification');
const living=calculateCarePlan('adoption',{...source,zaZyciem:'yes'},1);
assert.equal(living.parentalWeeks,65);
const livingMin=calculateCarePlan('adoption',{...source,childBirthDates:['2013-01-01'],zaZyciem:'yes'},1);
assert.equal(livingMin.parentalWeeks,62);
const singleWeek={id:'extra',owner:1,start:plan.entries[0].start,end:plan.entries[0].end,used:false};
assert.throws(()=>calculateCarePeriods(adopt,[plan.entries[0],singleWeek],true),/Nakładające/);
assert.throws(()=>calculateCarePeriods(near14,[{id:'late',owner:1,start:'2027-01-01',end:'2027-01-07',used:false}],false),/14/);
assert.throws(()=>calculateCarePeriods(adopt,Array.from({length:6},(_,i)=>({id:'x'+i,owner:1,start:'2027-06-01',end:'2027-06-07',used:false})),false),/5 części/);
assert.equal(careDocuments(foster,'dzialalnosc','standard').some(x=>x.title.includes('zasiłek')),true);
console.log('OK: adoption/foster source-backed calendar, ages 7/10/14, min9/38, 41/43, Za życiem, forms and 100/70/81.5 gross');
